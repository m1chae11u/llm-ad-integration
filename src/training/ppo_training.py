    @staticmethod
    def ensure_llamafactory_tuple_output(model, logger):
        import types, torch
        if hasattr(model, "_patched_forward_llf"):
            return model

        original_forward = model.forward
        def patched_forward(self, *args, **kwargs):
            return_dict = kwargs.pop("return_dict", True)
            out = original_forward(*args, return_dict=return_dict, **kwargs)

            if hasattr(out, "logits"):
                logits = out.logits
                pkv = getattr(out, "past_key_values", None)
                value = getattr(out, "value", None)

                if value is None:
                    bs = logits.shape[0]
                    sl = logits.shape[1] if logits.dim() > 1 else 1
                    value = torch.zeros(bs, sl, device=logits.device, dtype=logits.dtype)

                if isinstance(value, torch.Tensor):
                    if value.dim() == 1:
                        value = value.unsqueeze(1).expand(-1, logits.shape[1])
                    if value.dim() == 2 and value.shape[1] == 1:
                        value = value.expand(-1, logits.shape[1])

                return (logits, pkv, value)

            if isinstance(out, tuple):
                return (out + (None, None, None))[:3]

            if isinstance(out, dict):
                return (out.get("logits"), out.get("past_key_values"), out.get("value", out.get("values")))

            return (out, None, None)

        model.forward = types.MethodType(patched_forward, model)
        model._patched_forward_llf = True
        return model

    def prepare_dataloader(self, dataset, data_collator):
        import torch.utils.data

        # prefer preserved original dataset
        if getattr(self, "_original_train_dataset", None) is not None:
            if len(self._original_train_dataset) > 0:
                dataset = self._original_train_dataset
                self.dataset = dataset
                self.train_dataset = dataset

        if dataset is None or len(dataset) == 0:
            raise ValueError("❌ Cannot create dataloader with empty dataset")

        # ✅ use TrainingArguments batch size (matches your _reset_dataloader)
        bs = getattr(self.args, "per_device_train_batch_size", None)
        if bs is None:
            # last resort fallback
            bs = getattr(getattr(self, "training_args", None), "per_device_train_batch_size", 1)

        return torch.utils.data.DataLoader(
            dataset,
            batch_size=bs,
            collate_fn=data_collator,
            shuffle=True,
            drop_last=False,
            num_workers=getattr(self.args, "dataloader_num_workers", 0),
            pin_memory=getattr(self.args, "dataloader_pin_memory", False),
        )

    def _reset_dataloader(self):
        """Reset dataloader + iterator using ONE source of truth."""
        if getattr(self, "train_dataset", None) is None:
            raise RuntimeError("train_dataset not available. Set it before calling _reset_dataloader().")
        if getattr(self, "data_collator", None) is None:
            raise RuntimeError("data_collator not available.")

        # IMPORTANT: HF datasets + num_workers>0 is often pain. Start with 0.
        if hasattr(self.args, "dataloader_num_workers"):
            self.args.dataloader_num_workers = 0

        self.dataloader = self.prepare_dataloader(self.train_dataset, self.data_collator)
        self._dataloader_iter = iter(self.dataloader)

        bs = getattr(self.args, "per_device_train_batch_size", None)
        print(f"✅ Dataloader reset: {len(self.dataloader)} batches | batch_size={bs} | collator={type(self.data_collator).__name__}")

    def _make_batch(self):
        """Get the next batch from the dataloader, resetting if needed."""
        try:
            if self._dataloader_iter is None:
                self._reset_dataloader()
            batch = next(self._dataloader_iter)
            if batch is None:
                raise RuntimeError("Got None batch from dataloader")
            return batch
        except (StopIteration, UnboundLocalError):
            print("🔄 Dataloader exhausted, resetting iterator...")
            self._reset_dataloader()
            try:
                batch = next(self._dataloader_iter)
                if batch is None:
                    raise RuntimeError("Got None batch from dataloader after reset")
                return batch
            except StopIteration:
                raise RuntimeError("Dataloader is empty - no data available for training")
            except Exception as e:
                print(f"❌ Failed to get batch after reset: {e}")
                raise RuntimeError(f"Failed to get batch: {e}")
    
   

    @torch.no_grad()
    def get_inputs(self, batch):
        """Generate responses with and without ads."""
        # Handle both list-of-dicts and batched-dict formats from DataLoader
        if isinstance(batch, dict) and "vague_query" in batch:
            # Batched dict format - convert to list of dicts
            batch_size = len(batch["vague_query"])
            batch = [
                {key: batch[key][i] if isinstance(batch[key], (list, tuple)) else batch[key]
                 for key in batch.keys()}
                for i in range(batch_size)
            ]
        
        # Decode raw queries for logging
        raw_qs = [ex["vague_query"] for ex in batch]
        self._last_batch_raw_qs = raw_qs

        # Extract ad metadata
        ad_products  = [ex["ad_product"] for ex in batch]
        brands       = [ex["brand"] for ex in batch]
        urls         = [ex["url"] for ex in batch]
        descriptions = [ex["ad_description"] for ex in batch]
        dataset_idxs = [ex["dataset_idx"] for ex in batch]

        # Build prompts
        full_prompts_ad = []
        full_prompts_no_ad = []
        ad_texts = []

        for i, q in enumerate(raw_qs):
            ad_text = (
                f"Product: {ad_products[i]}\n"
                f"Brand:   {brands[i]}\n"
                f"URL:     {urls[i]}\n"
                f"Desc:    {descriptions[i]}"
            )
            full_prompts_ad.append(get_prompt_with_ad(q, ad_text))
            full_prompts_no_ad.append(get_prompt_without_ad(q))
            ad_texts.append(ad_text)

        self._last_batch_ad_texts = ad_texts
        self._last_batch_dataset_idxs = dataset_idxs

        # --- Use collator for tokenization & padding ---
        # Tokenize prompts explicitly for clarity and error handling
        batch_with_ad = self.data_collator([
            {"text": prompt, "dataset_idx": idx}
            for prompt, idx in zip(full_prompts_ad, dataset_idxs)
        ])
        batch_no_ad = self.data_collator([
            {"text": prompt, "dataset_idx": idx}
            for prompt, idx in zip(full_prompts_no_ad, dataset_idxs)
        ])

        # Get model - CRITICAL: Don't move it! It's already on the correct device.
        # Moving causes OOM because PyTorch creates a duplicate copy in memory.
        model = self.accelerator.unwrap_model(self.model)
        
        # Determine model's actual device
        # With device_map="auto", model should be on GPU
        # Check base model first (value head might be on different device)
        try:
            # Try to get device from base model (more reliable)
            if hasattr(model, 'pretrained_model'):
                # This is a model with value head - check base model
                base_model = model.pretrained_model
                model_device = next(base_model.parameters()).device
            elif hasattr(model, 'model'):
                # Some models wrap in .model attribute
                model_device = next(model.model.parameters()).device
            else:
                # Check multiple parameters to find the actual device
                devices = set()
                param_count = 0
                for param in model.parameters():
                    devices.add(param.device)
                    param_count += 1
                    if param_count >= 20:  # Check more parameters
                        break
                
                # Prefer GPU if available
                if torch.cuda.is_available() and any(d.type == "cuda" for d in devices):
                    model_device = torch.device("cuda")
                elif len(devices) == 1:
                    model_device = devices.pop()
                else:
                    # Use first GPU device found, or first device
                    cuda_devices = [d for d in devices if d.type == "cuda"]
                    model_device = cuda_devices[0] if cuda_devices else next(iter(devices))
        except (StopIteration, AttributeError, RuntimeError) as e:
            # Fallback: if GPU available, use GPU; otherwise CPU
            model_device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
            logger.debug(f"Device detection fallback: {e}")
        
        # Debug: log device info (only first time)
        if not hasattr(self, '_device_logged'):
            cur = getattr(self, "current_device", None) or getattr(self.accelerator, "device", None)
            logger.info(f"🔧 Model device: {model_device}, Current device: {cur}")
            if model_device.type == "cpu" and torch.cuda.is_available():
                logger.warning(f"⚠️ Model is on CPU but GPU is available - this will be very slow!")
            self._device_logged = True
        
        # Move inputs to model's device (not self.current_device which might be wrong)
        input_ids_ad = batch_with_ad["input_ids"].to(model_device)
        attention_mask_ad = batch_with_ad["attention_mask"].to(model_device)
        input_ids_no_ad = batch_no_ad["input_ids"].to(model_device)
        attention_mask_no_ad = batch_no_ad["attention_mask"].to(model_device)

        # --- Generate responses ---
        gen_kwargs = self.generation_config.to_dict()
        for k in ["skip_special_tokens", "max_length", "pad_token_id", "eos_token_id"]:
            gen_kwargs.pop(k, None)

        # Generate with ads
        gen_out_ad = model.generate(
            generation_config=self.generation_config,
            input_ids=input_ids_ad,
            attention_mask=attention_mask_ad,
            pad_token_id=self._custom_tokenizer.pad_token_id,
            **gen_kwargs,
        )

        # Generate without ads
        gen_out_no_ad = model.generate(
            generation_config=self.generation_config,
            input_ids=input_ids_no_ad,
            attention_mask=attention_mask_no_ad,
            pad_token_id=self._custom_tokenizer.pad_token_id,
            **gen_kwargs,
        )

        # --- Extract responses relative to prompt length ---
        response_tensors_ad = []
        response_tensors_no_ad = []
        for i in range(input_ids_ad.size(0)):
            prompt_len_ad = attention_mask_ad[i].sum().item()
            prompt_len_no = attention_mask_no_ad[i].sum().item()
            response_tensors_ad.append(gen_out_ad[i, prompt_len_ad:])
            response_tensors_no_ad.append(gen_out_no_ad[i, prompt_len_no:])

        # Store no-ad responses for detectability
        decoded_no_ad = [
            self._custom_tokenizer.decode(t, skip_special_tokens=True)
            for t in response_tensors_no_ad
        ]
        self.no_ad_responses.extend(decoded_no_ad)
        self._last_batch_no_ads = decoded_no_ad

        for t in decoded_no_ad:
            PPO_NO_AD_BUFFER.append(t)

        # Return query tensors (with-ad prompts) and response tensors
        # Ensure they are lists of tensors (not batched tensors)
        query_tensors = [input_ids_ad[i].clone() for i in range(input_ids_ad.size(0))]
        response_tensors = [r.clone() for r in response_tensors_ad]
        return query_tensors, response_tensors

    def prepare_model_inputs(self, queries, responses):
        """
        Build model_inputs from query/response token tensors without any text decode/re-tokenize.

        Args:
            queries: List[torch.Tensor], each shape [q_len]
            responses: List[torch.Tensor], each shape [r_len]
        Returns:
            Dict[str, torch.Tensor]: {"input_ids": [B, T], "attention_mask": [B, T]}
            Both tensors are placed on the policy model's device.
        """
        import torch

        # ✅ policy device (works with accelerate wrappers)
        policy_model = self.accelerator.unwrap_model(self.model) if hasattr(self, "accelerator") else self.model
        policy_device = next(policy_model.parameters()).device

        # Defensive: allow single tensors too
        if isinstance(queries, torch.Tensor):
            queries = [queries]
        if isinstance(responses, torch.Tensor):
            responses = [responses]

        if len(queries) != len(responses):
            raise ValueError(f"queries/responses length mismatch: {len(queries)} vs {len(responses)}")

        # pad_token_id fallback chain
        tok = getattr(self, "_custom_tokenizer", None) or getattr(self, "tokenizer", None)
        if tok is not None and tok.pad_token_id is not None:
            pad_token_id = tok.pad_token_id
        elif tok is not None and tok.eos_token_id is not None:
            pad_token_id = tok.eos_token_id
        else:
            pad_token_id = 0

        input_ids_list = []
        attn_list = []

        for q, r in zip(queries, responses):
            if not isinstance(q, torch.Tensor) or not isinstance(r, torch.Tensor):
                raise TypeError("prepare_model_inputs expects token tensors (queries/responses).")

            q = q.to(policy_device)
            r = r.to(policy_device)

            full = torch.cat([q, r], dim=0)  # [T]
            input_ids_list.append(full)

            attn = torch.ones_like(full, dtype=torch.long, device=policy_device)  # [T]
            attn_list.append(attn)

        max_len = max(t.size(0) for t in input_ids_list)
        batch_size = len(input_ids_list)

        input_ids = torch.full(
            (batch_size, max_len),
            pad_token_id,
            dtype=torch.long,
            device=policy_device,
        )
        attention_mask = torch.zeros(
            (batch_size, max_len),
            dtype=torch.long,
            device=policy_device,
        )

        for i, (seq, attn) in enumerate(zip(input_ids_list, attn_list)):
            seq_len = seq.size(0)
            input_ids[i, :seq_len] = seq
            attention_mask[i, :seq_len] = attn

        return {"input_ids": input_ids, "attention_mask": attention_mask}

